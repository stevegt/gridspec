package rules

import (
	"context"
	"fmt"
	"net/http"
	"net/url"
	"path"
	"path/filepath"
	"strings"

	"github.com/promisegrid/gridspec/internal/diag"
	"github.com/promisegrid/gridspec/internal/model"
	"github.com/promisegrid/gridspec/internal/source"
)

func checkLinks(ctx Context, idx Index) []diag.Diagnostic {
	var ds []diag.Diagnostic
	inbound := make(map[string]int)
	for _, graph := range ctx.IR.Graphs {
		type linkDeclaration struct {
			ID       string
			URL      string
			Location model.Location
		}
		declarations := []linkDeclaration{{ID: graph.ID, URL: graph.URL, Location: graph.Location}}
		for _, element := range append(append([]model.Element(nil), graph.Nodes...), graph.Edges...) {
			declarations = append(declarations, linkDeclaration{ID: element.ID, URL: element.URL, Location: element.Location})
		}
		for _, element := range declarations {
			if element.URL == "" {
				continue
			}
			u, err := url.Parse(element.URL)
			if err != nil {
				ds = append(ds, diagnostic("SDV140", diag.SeverityError, element.Location, "invalid URL: "+err.Error(), "use a relative Markdown path with an optional anchor", element.ID, false))
				continue
			}
			if u.Scheme == "http" || u.Scheme == "https" {
				if !ctx.Config.LinkPolicy.AllowRemote {
					ds = append(ds, diagnostic("SDV141", diag.SeverityError, element.Location, "remote Markdown URL is forbidden by link_policy", "use a repository-local document or allow remote links explicitly", element.ID, true))
					continue
				}
				if !ctx.Online {
					severity := diag.SeverityWarning
					if ctx.Profile.BuildReady {
						severity = diag.SeverityError
					}
					ds = append(ds, diagnostic("SDV142", severity, element.Location, "remote Markdown accessibility was not checked", "run gridspec vet --online", element.ID, true))
					continue
				}
				if err := probeURL(ctx, element.URL); err != nil {
					ds = append(ds, diagnostic("SDV143", diag.SeverityError, element.Location, "remote Markdown is inaccessible: "+err.Error(), "repair or replace the URL", element.ID, true))
				}
				continue
			}
			if u.Scheme != "" {
				ds = append(ds, diagnostic("SDV144", diag.SeverityError, element.Location, fmt.Sprintf("URL scheme %q is not supported", u.Scheme), "use a local Markdown path or http(s) when enabled", element.ID, false))
				continue
			}
			docPath := path.Clean(path.Join(path.Dir(graph.Location.File), filepath.ToSlash(u.Path)))
			doc, exists := ctx.Documents[docPath]
			if !exists {
				ds = append(ds, diagnostic("SDV145", diag.SeverityError, element.Location, fmt.Sprintf("referenced Markdown %q does not exist in the module", docPath), "add the file or correct URL", element.ID, false))
				continue
			}
			inbound[docPath]++
			if u.Fragment != "" {
				fragment, err := url.PathUnescape(u.Fragment)
				if err != nil {
					ds = append(ds, diagnostic("SDV146", diag.SeverityError, element.Location, "invalid URL anchor escaping", "use a valid Markdown heading anchor", element.ID, false))
				} else if _, ok := doc.Anchors[fragment]; !ok {
					ds = append(ds, diagnostic("SDV147", diag.SeverityError, element.Location, fmt.Sprintf("Markdown anchor #%s does not exist in %s", fragment, docPath), "link to a heading generated by the documented slug rules", element.ID, false))
				}
			}
			if ctx.Config.LinkPolicy.RequireBacklinks && !documentLinksTo(doc, graph.Location.File) {
				ds = append(ds, diagnostic("SDV148", diag.SeverityError, element.Location, fmt.Sprintf("%s does not link back to its DOT source", docPath), "add a relative Markdown link to the owning .dot file", element.ID, true))
			}
		}
	}
	for docPath, doc := range ctx.Documents {
		if inbound[docPath] == 0 && len(doc.Contracts) > 0 {
			ds = append(ds, diagnostic("SDV149", diag.SeverityWarning, model.Location{File: docPath, Line: 1, Column: 1}, "Markdown contract file is not referenced by any DOT URL", "link the contract from the declaration it extends", "", true))
		}
	}
	return ds
}

func probeURL(ctx Context, raw string) error {
	timeout := ctx.Config.LinkPolicy.RemoteTimeout
	client := &http.Client{Timeout: timeout}
	req, err := http.NewRequestWithContext(context.Background(), http.MethodHead, raw, nil)
	if err != nil {
		return err
	}
	resp, err := client.Do(req)
	if err != nil {
		return err
	}
	if resp.StatusCode == http.StatusMethodNotAllowed || resp.StatusCode == http.StatusNotImplemented {
		resp.Body.Close()
		req, err = http.NewRequestWithContext(context.Background(), http.MethodGet, raw, nil)
		if err != nil {
			return err
		}
		req.Header.Set("Range", "bytes=0-1023")
		resp, err = client.Do(req)
		if err != nil {
			return err
		}
	}
	defer resp.Body.Close()
	if resp.StatusCode < 200 || resp.StatusCode >= 400 {
		return fmt.Errorf("HTTP %s", resp.Status)
	}
	contentType := resp.Header.Get("Content-Type")
	if contentType != "" && !strings.Contains(contentType, "markdown") && !strings.Contains(contentType, "text/plain") && !strings.Contains(contentType, "text/") {
		return fmt.Errorf("content type %q is not Markdown-like", contentType)
	}
	return nil
}

func documentLinksTo(doc source.Document, target string) bool {
	for _, link := range doc.Links {
		u, err := url.Parse(link.Destination)
		if err != nil || u.Scheme != "" || u.Path == "" {
			continue
		}
		resolved := path.Clean(path.Join(path.Dir(doc.Path), filepath.ToSlash(u.Path)))
		if resolved == filepath.ToSlash(target) {
			return true
		}
	}
	return false
}
